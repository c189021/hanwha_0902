# =============================================================================
# 03_lambda.py  -  람다(lambda) : 이름 없는 한 줄 함수
# =============================================================================
# 형식:  lambda 인자1, 인자2, ... : 반환할_식
#
#   def add(a, b):          람다로 쓰면
#       return a + b        add = lambda a, b: a + b
#
# 한 줄로 끝나는 간단한 함수를, 특히 "다른 함수의 인자로" 넘길 때 자주 쓴다.
# 로직이 길거나 여러 줄이면 그냥 def 로 함수를 만드는 게 낫다.
# =============================================================================

# -----------------------------------------------------------------------------
# 1) 변수에 담아 쓰기 (개념 이해용. 실무에선 잘 안 함)
# -----------------------------------------------------------------------------
square = lambda x: x * x
print(square(5))        # 25

is_adult = lambda age: age >= 19
print(is_adult(20))     # True


# -----------------------------------------------------------------------------
# 2) sorted() 의 key 로 넘기기  <- 가장 흔한 용도
# -----------------------------------------------------------------------------
users = [
    {"name": "홍길동", "age": 20},
    {"name": "김철수", "age": 17},
    {"name": "이영희", "age": 25},
]

# 나이 기준 오름차순 정렬
by_age = sorted(users, key=lambda u: u["age"])
for u in by_age:
    print(u["name"], u["age"])

# 나이 기준 내림차순
by_age_desc = sorted(users, key=lambda u: u["age"], reverse=True)
print([u["name"] for u in by_age_desc])


# -----------------------------------------------------------------------------
# 3) map() / filter() 와 함께
# -----------------------------------------------------------------------------
nums = [1, 2, 3, 4, 5, 6]

# map : 각 원소를 변환
doubled = list(map(lambda n: n * 2, nums))
print(doubled)          # [2, 4, 6, 8, 10, 12]

# filter : 조건이 True인 원소만 남김
evens = list(filter(lambda n: n % 2 == 0, nums))
print(evens)            # [2, 4, 6]

# 참고: 위 두 개는 리스트 컴프리헨션으로도 똑같이 쓸 수 있고,
#       보통 그게 더 읽기 쉽다.
doubled2 = [n * 2 for n in nums]
evens2 = [n for n in nums if n % 2 == 0]


# -----------------------------------------------------------------------------
# 4) max() / min() 의 key
# -----------------------------------------------------------------------------
oldest = max(users, key=lambda u: u["age"])
print(f"가장 나이 많은 사람: {oldest['name']}")
