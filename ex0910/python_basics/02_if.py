# =============================================================================
# 02_if.py  -  제어문 if / elif / else
# =============================================================================
# 조건이 참(True)이냐 거짓(False)이냐에 따라 실행 흐름을 나누는 문법.
# 들여쓰기(보통 공백 4칸)로 "이 블록이 if에 속한다"를 표시한다.
# =============================================================================

# -----------------------------------------------------------------------------
# 1) 기본형
# -----------------------------------------------------------------------------
age = 20

if age >= 19:
    print("성인입니다.")
else:
    print("미성년자입니다.")


# -----------------------------------------------------------------------------
# 2) 여러 갈래 (elif)
# -----------------------------------------------------------------------------
score = 82

if score >= 90:
    grade = "A"
elif score >= 80:      # 위 조건이 False일 때만 검사
    grade = "B"
elif score >= 70:
    grade = "C"
else:
    grade = "F"

print(f"점수 {score} -> 학점 {grade}")


# -----------------------------------------------------------------------------
# 3) 참/거짓으로 취급되는 값들 (truthy / falsy)
# -----------------------------------------------------------------------------
# 아래 값들은 if에서 False로 취급된다:
#   0, 0.0, "" (빈 문자열), [] (빈 리스트), {} (빈 딕셔너리), None
name = ""

if name:                       # 빈 문자열이면 False
    print(f"이름: {name}")
else:
    print("이름이 비어 있습니다.")

items = [1, 2, 3]
if items:                      # 리스트에 뭔가 있으면 True
    print(f"{len(items)}개의 항목이 있습니다.")


# -----------------------------------------------------------------------------
# 4) and / or / not  과  in
# -----------------------------------------------------------------------------
user_text = "오늘 서울 날씨 알려줘"

if "날씨" in user_text and "서울" in user_text:
    print("서울 날씨를 조회합니다.")

if not user_text:
    print("입력이 없습니다.")


# -----------------------------------------------------------------------------
# 5) 삼항 연산자 (한 줄 if)
# -----------------------------------------------------------------------------
# 형식:  값A if 조건 else 값B
age = 15
label = "성인" if age >= 19 else "미성년자"
print(label)

