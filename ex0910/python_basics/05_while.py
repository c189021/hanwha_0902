# 05_while.py  -  반복문 while
# =============================================================================
# "조건이 참인 동안" 블록을 계속 반복한다.
# 반복 횟수가 정해져 있으면 for, "언제 끝날지 모르고 조건으로 끝내야" 하면 while.
#
#   while 조건:
#       반복할_코드
#       (조건을 언젠가 False로 만들 코드가 반드시 있어야 함 -> 아니면 무한 루프)
# =============================================================================

# -----------------------------------------------------------------------------
# 1) 기본형 : 카운터를 직접 증가
# -----------------------------------------------------------------------------
i = 1
while i <= 5:
    print(f"{i}번째 반복")
    i += 1          # 이게 없으면 i가 영원히 1 -> 무한 루프
print("반복 종료")


# -----------------------------------------------------------------------------
# 2) break : 조건과 상관없이 즉시 탈출
# -----------------------------------------------------------------------------
total = 0
n = 1
while True:                 # 일부러 무한 루프로 만들고, 안에서 break로 끊기
    total += n
    if total > 30:
        print(f"합계가 {total} 이 되어 중단 (n={n})")
        break
    n += 1


# -----------------------------------------------------------------------------
# 3) continue : 이번 회차만 건너뛰고 다음 반복으로
# -----------------------------------------------------------------------------
num = 0
while num < 10:
    num += 1
    if num % 2 == 0:       # 짝수면
        continue           # 아래 print를 건너뛴다
    print(f"홀수: {num}")


# -----------------------------------------------------------------------------
# 4) while ~ else : break 없이 조건이 False가 되어 정상 종료하면 else 실행
# -----------------------------------------------------------------------------
attempt = 0
while attempt < 3:
    print(f"시도 {attempt + 1}")
    attempt += 1
else:
    print("3번 모두 시도 완료 (break 없이 끝남)")


