# =============================================================================
# 01_dict_typing.py  -  딕셔너리에 "타입"을 붙여 쓰기
# =============================================================================
# 딕셔너리(dict)는 "키: 값" 쌍을 모아둔 자료형이다.
# 파이썬은 타입을 강제하진 않지만, 타입 힌트를 달아두면
#   - 편집기 자동완성 / 오타 경고
#   - 협업 시 "이 dict의 모양"을 문서처럼 전달
# 하는 장점이 있다.
# =============================================================================

# -----------------------------------------------------------------------------
# 1) 기본 딕셔너리
# -----------------------------------------------------------------------------
user = {"name": "홍길동", "age": 20}

print(user["name"])          # 값 꺼내기 -> 홍길동
print(user.get("email"))     # 없는 키는 get() 쓰면 None (에러 안 남)
print(user.get("email", "이메일 없음"))  # 기본값 지정

user["age"] = 21             # 값 수정
user["email"] = "hong@test.com"  # 새 키 추가
del user["email"]            # 키 삭제

for key, value in user.items():   # 키-값 함께 순회
    print(f"{key} = {value}")


# -----------------------------------------------------------------------------
# 2) 타입 힌트를 붙인 딕셔너리 (dict[키타입, 값타입])
# -----------------------------------------------------------------------------
# "문자열 키 -> 정수 값" 딕셔너리라는 뜻
scores: dict[str, int] = {
    "국어": 90,
    "영어": 85,
    "수학": 100,
}

total = sum(scores.values())
avg = total / len(scores)
print(f"총점 {total}, 평균 {avg:.1f}")


# -----------------------------------------------------------------------------
# 3) TypedDict  -  "이 dict는 이런 키들을 가진다"를 명확히 정의
# -----------------------------------------------------------------------------
# FastAPI의 Pydantic 모델과 비슷한 느낌. 키 이름/타입을 미리 못박아 둔다.
from typing import TypedDict


class Product(TypedDict):
    name: str
    price: int
    in_stock: bool


item: Product = {
    "name": "커피",
    "price": 4500,
    "in_stock": True,
}
# item["price"] = "비싸요"  <- 편집기가 "int 자리에 str" 이라고 경고해 준다.

print(f'{item["name"]} : {item["price"]}원 (재고: {item["in_stock"]})')


# -----------------------------------------------------------------------------
# 4) 중첩 딕셔너리 (dict 안에 dict / list)
# -----------------------------------------------------------------------------
classroom: dict[str, dict[str, int]] = {
    "홍길동": {"국어": 90, "수학": 80},
    "김철수": {"국어": 70, "수학": 95},
}

for name, subject_scores in classroom.items():
    avg = sum(subject_scores.values()) / len(subject_scores)
    print(f"{name} 평균: {avg:.1f}")
