# =============================================================================
# proj_fastapi/chat.py  -  챗봇 백엔드(답변을 만들어 주는 서버)
# =============================================================================
# [전체 구조]
#   Streamlit(chat_app.py)  ──HTTP POST──▶  FastAPI(chat.py, 이 파일)
#                           ◀──JSON 응답──
#
#   - Streamlit : 채팅 화면을 그리고, 내가 친 메시지를 이 서버로 보냄
#   - FastAPI   : 메시지를 보고 규칙에 맞는 답변을 골라서 돌려줌
#
# [실행 방법]
#   cd proj_fastapi
#   uvicorn chat:app --reload            # 주소: http://127.0.0.1:8000
# =============================================================================

from fastapi import FastAPI
from pydantic import BaseModel

app = FastAPI()


# -----------------------------------------------------------------------------
# 요청 데이터 모양: 사용자가 보낸 메시지 한 줄
#   예: {"text": "안녕"}
# -----------------------------------------------------------------------------
class Message(BaseModel):
    text: str


# -----------------------------------------------------------------------------
# GET /  -  서버가 살아있는지 확인용
# -----------------------------------------------------------------------------
@app.get("/")
def read_root():
    return {"message": "챗봇 서버가 정상 동작 중입니다."}


# -----------------------------------------------------------------------------
# POST /chat  -  메시지를 받아서 답변을 만들어 주는 곳
# -----------------------------------------------------------------------------
# (지금은 아주 간단하게 '단어가 들어있으면 이렇게 답한다' 수준.
#  나중에 여기 자리에 진짜 AI 모델을 넣으면 됨.)
@app.post("/chat")
def chat(msg: Message):
    user_text = msg.text

    if "안녕" in user_text:
        reply = "안녕하세요! 반가워요."
    elif "이름" in user_text:
        reply = "저는 아주 간단한 챗봇이에요."
    elif "날씨" in user_text:
        reply = "날씨는 저도 잘 몰라요. 창밖을 봐주세요."
    elif "잘가" in user_text or "바이" in user_text:
        reply = "안녕히 가세요!"
    else:
        reply = f'"{user_text}" 라고 하셨네요. 아직 잘 이해하지 못했어요.'

    # Streamlit(chat_app.py)에서 result["reply"] 로 꺼내 씀
    return {"reply": reply}
