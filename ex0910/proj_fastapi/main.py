# =============================================================================
# proj_fastapi/main.py  -  백엔드(API 서버) 역할
# =============================================================================
# [전체 구조]
#   Streamlit(app.py, 프론트엔드)  ──HTTP 요청──▶  FastAPI(main.py, 백엔드)
#                                  ◀──JSON 응답──
#
#   - Streamlit : 사용자 화면(입력 폼)을 그리고, 입력값을 이 서버로 전송
#   - FastAPI   : 전달받은 데이터를 처리(비즈니스 로직 / AI 추론)하고 결과 반환
#
# [실행 방법]
#   cd proj_fastapi
#   uvicorn main:app --reload            # 기본 주소: http://127.0.0.1:8000
#   (자동 생성 API 문서: http://127.0.0.1:8000/docs)
# =============================================================================

from fastapi import FastAPI          # 웹 API 프레임워크
from pydantic import BaseModel       # 요청 본문(JSON)의 형식 검증용 모델

# FastAPI 애플리케이션 객체 생성 (uvicorn이 이 'app'을 찾아서 구동함)
app = FastAPI()


# -----------------------------------------------------------------------------
# 요청 데이터 스키마 정의
# -----------------------------------------------------------------------------
# 클라이언트(Streamlit)가 POST로 보내는 JSON의 구조를 명시한다.
#   예: {"name": "홍길동", "age": 20}
# - 타입이 맞지 않거나 필드가 빠지면 FastAPI가 자동으로 422 에러를 응답한다.
class UserInput(BaseModel):
    name: str   # 이름 (문자열)
    age: int    # 나이 (정수)


# -----------------------------------------------------------------------------
# GET /  -  서버 상태 확인용 엔드포인트 (헬스 체크)
# -----------------------------------------------------------------------------
# 브라우저나 클라이언트가 루트 주소로 접속했을 때 서버가 살아있는지 확인하는 용도.
@app.get("/")
def read_root():
    return {"message": "FastAPI 서버가 정상 동작 중입니다."}


# -----------------------------------------------------------------------------
# POST /predict  -  실제 데이터 처리 엔드포인트 (Streamlit이 호출하는 곳)
# -----------------------------------------------------------------------------
# 흐름:
#   1) Streamlit이 {"name":..., "age":...} JSON을 POST로 전송
#   2) FastAPI가 UserInput 모델로 자동 파싱 및 검증 -> data 인자로 전달
#   3) 아래 로직에서 결과를 계산
#   4) dict를 return 하면 FastAPI가 JSON으로 직렬화해서 응답
@app.post("/predict")
def process_data(data: UserInput):
    # ↓↓↓ 비즈니스 로직 및 AI 모델 추론 처리 위치 ↓↓↓
    # (지금은 예시로 "성인 여부"만 판별. 실제로는 여기서 모델 예측 등을 수행)
    is_adult = data.age >= 19
    message = f"안녕하세요 {data.name}님! " + ("성인입니다." if is_adult else "미성년자입니다.")

    # 응답 JSON (Streamlit의 app.py에서 result['result_message'] 등으로 사용)
    return {
        "status": "success",
        "result_message": message,
        "is_adult": is_adult
    }
